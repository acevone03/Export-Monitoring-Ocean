import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { randomUUID } from "node:crypto";

// File storage behind an interface so local disk can later become S3 or similar.
export interface FileStorage {
  put(data: Buffer, ext: string): Promise<string>; // returns storage key
  get(key: string): Promise<Buffer>;
}

export class LocalDiskStorage implements FileStorage {
  constructor(private readonly root: string) {}

  async put(data: Buffer, ext: string): Promise<string> {
    const now = new Date();
    const dir = `${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, "0")}`;
    const key = `${dir}/${randomUUID()}${ext}`;
    await mkdir(path.join(this.root, dir), { recursive: true });
    await writeFile(path.join(this.root, key), data);
    return key;
  }

  async get(key: string): Promise<Buffer> {
    // Keys are generated by put(); still refuse anything that escapes the root.
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error("Invalid storage key");
    return readFile(full);
  }
}

export const storage: FileStorage = new LocalDiskStorage(process.env.UPLOAD_DIR || "./uploads");

// Proofs are screenshots or PDFs. Anything else is rejected.
export const ALLOWED_UPLOADS: Record<string, string> = {
  "image/png": ".png",
  "image/jpeg": ".jpg",
  "image/webp": ".webp",
  "application/pdf": ".pdf",
};
export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;
